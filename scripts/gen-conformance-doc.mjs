#!/usr/bin/env node
// Generates docs/conformance.md from the titles of the tests in test/conformance.
// Titles look like: C<n>[b] <rule> [<doc url>] for Anthropic Messages (Claude Code), R<n>[b] for OpenAI Responses (Codex).
// Usage: node scripts/gen-conformance-doc.mjs > docs/conformance.md
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = join(import.meta.dirname, '..');
const dir = join(root, 'test', 'conformance');

function walk(d) {
  return readdirSync(d).flatMap((f) => {
    const p = join(d, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.test.ts') ? [p] : [];
  });
}

const TITLE = /^\s*(?:test|it)\(\s*(['"`])((?:C|R)(\d+)([a-z]?) .+?) \[(https?:\/\/[^\]\s]+)\]\1/;

const rows = new Map(); // key: prefix + number
for (const file of walk(dir).sort()) {
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const m = TITLE.exec(line);
    if (!m) continue;
    const [, , full, num, , url] = m;
    const id = full.split(' ')[0];
    const rule = full.slice(id.length + 1);
    const key = `${id[0]}${num}`;
    const row = rows.get(key) ?? { key, n: Number(num), kind: id[0], rules: [], urls: new Set(), files: new Set() };
    row.rules.push(id === key ? rule : `(${id}) ${rule}`);
    row.urls.add(url);
    row.files.add(relative(root, file));
    rows.set(key, row);
  }
}

const sorted = [...rows.values()].sort((a, b) => (a.kind === b.kind ? a.n - b.n : a.kind < b.kind ? -1 : 1));
const esc = (s) => s.replaceAll('|', '\\|');
const out = [];
out.push('# Conformance');
out.push('');
out.push('Generated by `node scripts/gen-conformance-doc.mjs` from the test titles in `test/conformance/`. Do not edit by hand.');
out.push('Each rule is a test that sends recorded or synthetic traffic through tokenyard in front of a mock provider and compares what the provider received and what the client got back.');
out.push('C rules cover Anthropic Messages (Claude Code), R rules OpenAI Responses (Codex).');
out.push('Bodies the gateway cannot price or read (an unpriced model, no model, JSON that does not parse) are forwarded unchanged only when no enforced budget level applies; under one they are refused before admit (security review A2, A5). C1, C11 and the parse-error rules therefore run with every budget in audit mode.');
out.push('');
out.push('| # | Rule | Source | Test |');
out.push('|---|---|---|---|');
for (const r of sorted) {
  const src = [...r.urls].map((u) => `[doc](${u})`).join(' ');
  const files = [...r.files].map((f) => `\`${f}\``).join(' ');
  out.push(`| ${r.key} | ${r.rules.map(esc).join('<br>')} | ${src} | ${files} |`);
}
out.push('');
out.push('## Client versions checked by hand');
out.push('');
out.push('Dates are UTC.');
out.push('');
out.push('| Client | Version | Date | Result |');
out.push('|---|---|---|---|');
out.push('| Claude Code | 2.1.316 | 2026-11-02 | `claude -p "say hi"` through tokenyard against the mock worked; it sent `POST /v1/messages?beta=true`. Then live against the real API through the live harness: 5 sessions with subagents, tool calls and WebSearch, per-request tokens equal to Claude Code\'s own OTel events on the 11 requests where both were captured; see `test/live/claude-code.live.md` |');
out.push('| Codex | 0.166.0 | 2026-11-02 | `codex exec` with `wire_api = "responses"` through the live harness against the real OpenAI API (gpt-5.4-mini): a one-line edit in a scratch clone, 3 billed requests; see `test/live/codex.live.md` |');
out.push('| Claude Code | 2.1.317 | 2026-11-03 | Live through the live harness: 6 sessions on Haiku 5.5 and Opus 5.5 with Explore and general-purpose subagents (two in parallel), file edits, Bash, `/compact` and `--resume`; per-request tokens equal to Claude Code\'s OTel `api_request` events on all 42 billed requests, cost within 1.79 micro-USD in total; budget block shown at once with no retries; see `test/live/claude-code.live.md`, run 2 |');
out.push('| Codex | 0.166.0 | 2026-11-03 | `codex exec` live again (gpt-5.4-mini, 4 billed requests); it sent no `Content-Encoding` to the API-key base URL; the budget block printed at once without retries; see `test/live/codex.live.md`, run 2 |');
out.push('| Claude Code | 2.1.318 | 2026-11-04 | `claude -p "say hi"` through tokenyard (`serve --dev-upstream`) against the mock: 200, streamed reply, usage settled from the final event (cache write 21,391, output 16), 8 ms added time to first byte; conformance suite 42 of 42 on the same day |');
out.push('');
process.stdout.write(out.join('\n'));
